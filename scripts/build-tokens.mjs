// Generates every file derived from src/design/palette.mjs:
//   src/styles/tokens.css          CSS custom properties (--ms-*)
//   public/favicon.svg             the bell mark, switching colours with the OS theme
//   src/assets/logo-light.svg      header logo for light mode
//   src/assets/logo-dark.svg       header logo for dark mode
// Usage: node scripts/build-tokens.mjs           write the files
//        node scripts/build-tokens.mjs --check   exit 1 if any file is out of date
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fonts, palette } from '../src/design/palette.mjs';

const fromRoot = (relativePath) => fileURLToPath(new URL(`../${relativePath}`, import.meta.url));

/** camelCase -> kebab-case, e.g. boardInkMuted -> board-ink-muted */
const toKebab = (name) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

/** @param {Record<string, string>} colours */
const declarations = (colours) =>
	Object.entries(colours)
		.map(([name, value]) => `\t--ms-${toKebab(name)}: ${value};`)
		.join('\n');

export function renderTokensCss() {
	const fontDeclarations = Object.entries(fonts)
		.map(([name, value]) => `\t--ms-font-${name}: ${value};`)
		.join('\n');

	// Starlight convention: :root is the dark theme, [data-theme='light'] overrides it.
	return `/* GENERATED by scripts/build-tokens.mjs from src/design/palette.mjs. Do not edit by hand. */

:root {
${fontDeclarations}
${declarations(palette.dark)}
}

:root[data-theme='light'] {
${declarations(palette.light)}
}

/* Print always uses the light theme: dark boards and pages waste ink and print badly. */
@media print {
	:root,
	:root[data-theme='light'] {
${declarations(palette.light).replace(/^\t/gm, '\t\t')}
	}
}
`;
}

// ── Brand mark: a smooth bell (no cusp at the peak) with the mean marked in μ pink on the axis ──
const BELL_PATH = 'M2 24 C6 24, 8 23, 10 20 C12 17, 13.5 4, 16 4 C18.5 4, 20 17, 22 20 C24 23, 26 24, 30 24';
const GENERATED_SVG_NOTE = '<!-- GENERATED by scripts/build-tokens.mjs from src/design/palette.mjs. Do not edit by hand. -->';

/** @param {{ ink: string, mu: string }} colours */
function renderBellSvg({ ink, mu }) {
	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" fill="none" role="img" aria-label="MathSignal">
${GENERATED_SVG_NOTE}
<path d="${BELL_PATH}" stroke="${ink}" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round"/>
<circle cx="16" cy="28" r="2.25" fill="${mu}"/>
</svg>
`;
}

export function renderFaviconSvg() {
	// Browser tabs follow the OS theme, not the site toggle, so the favicon switches with prefers-color-scheme.
	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" fill="none">
${GENERATED_SVG_NOTE}
<style>
path { stroke: ${palette.light.ink}; }
circle { fill: ${palette.light.mu}; }
@media (prefers-color-scheme: dark) {
	path { stroke: ${palette.dark.ink}; }
	circle { fill: ${palette.dark.mu}; }
}
</style>
<path d="${BELL_PATH}" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round"/>
<circle cx="16" cy="28" r="2.25"/>
</svg>
`;
}

/** Every generated file and its expected contents. */
export function generatedFiles() {
	return [
		{ path: 'src/styles/tokens.css', content: renderTokensCss() },
		{ path: 'public/favicon.svg', content: renderFaviconSvg() },
		{ path: 'src/assets/logo-light.svg', content: renderBellSvg({ ink: palette.light.ledgeInk, mu: palette.light.mu }) },
		{ path: 'src/assets/logo-dark.svg', content: renderBellSvg({ ink: palette.dark.ledgeInk, mu: palette.dark.mu }) },
	];
}

/** Paths of generated files whose contents on disk differ from what the palette produces. */
export async function staleGeneratedFiles() {
	const stale = [];
	for (const file of generatedFiles()) {
		const current = await readFile(fromRoot(file.path), 'utf8').catch(() => '');
		if (current.replace(/\r\n/g, '\n') !== file.content) stale.push(file.path);
	}
	return stale;
}

async function main() {
	if (process.argv.includes('--check')) {
		const stale = await staleGeneratedFiles();
		if (stale.length > 0) {
			console.error(`Out of date: ${stale.join(', ')}. Run \`npm run tokens\`.`);
			process.exit(1);
		}
		console.log('Generated design files are up to date.');
		return;
	}
	for (const file of generatedFiles()) {
		await mkdir(dirname(fromRoot(file.path)), { recursive: true });
		await writeFile(fromRoot(file.path), file.content, 'utf8');
		console.log(`Wrote ${file.path}`);
	}
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	main().catch((error) => {
		console.error('Failed to build design tokens:', error);
		process.exit(1);
	});
}
