// Generates src/styles/tokens.css from src/design/palette.mjs.
// Usage: node scripts/build-tokens.mjs           write the file
//        node scripts/build-tokens.mjs --check   exit 1 if the file is out of date
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { fonts, palette } from '../src/design/palette.mjs';

const OUTPUT_PATH = fileURLToPath(new URL('../src/styles/tokens.css', import.meta.url));

/** camelCase -> kebab-case, e.g. boardInkMuted -> board-ink-muted */
const toKebab = (name) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

/** @param {Record<string, string>} colours */
const declarations = (colours) =>
	Object.entries(colours)
		.map(([name, value]) => `\t--ms-${toKebab(name)}: ${value};`)
		.join('\n');

export function renderTokensCss() {
	const fontDeclarations = Object.entries(fonts)
		.map(([name, value]) => `\t--ms-font-${name}: ${value};`)
		.join('\n');

	// Starlight convention: :root is the dark theme, [data-theme='light'] overrides it.
	return `/* GENERATED by scripts/build-tokens.mjs from src/design/palette.mjs. Do not edit by hand. */

:root {
${fontDeclarations}
${declarations(palette.dark)}
}

:root[data-theme='light'] {
${declarations(palette.light)}
}
`;
}

async function main() {
	const expected = renderTokensCss();
	const isCheck = process.argv.includes('--check');
	if (!isCheck) {
		await writeFile(OUTPUT_PATH, expected, 'utf8');
		console.log(`Wrote ${OUTPUT_PATH}`);
		return;
	}
	const current = await readFile(OUTPUT_PATH, 'utf8').catch(() => '');
	if (current.replace(/\r\n/g, '\n') !== expected) {
		console.error('src/styles/tokens.css is out of date. Run `npm run tokens`.');
		process.exit(1);
	}
	console.log('tokens.css is up to date.');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	main().catch((error) => {
		console.error('Failed to build design tokens:', error);
		process.exit(1);
	});
}
