const BY_KEY = new Map(NOTATION.map((entry) => [entry.key, entry]));

/** @param {string} key */
export function getNotation(key) {
	const entry = BY_KEY.get(key);
	if (!entry) throw new Error(`Unknown notation key "${key}". Add it to src/data/notation.mjs.`);
	return entry;
}
